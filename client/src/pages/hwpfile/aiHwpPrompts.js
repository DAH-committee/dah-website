/** 매 전송마다 붙는 "지금 화면" 맥락 */
export function buildHwpContext({ info, version, selection, selText, page, pageCount, canEdit, viewingOld }) {
  const lines = []
  if (info) lines.push(`파일: ${info.title || ''} (${info.format || '?'}, ${pageCount || info.page_count || '?'}쪽, 버전 ${version})`)
  if (info?.render_mode) lines.push(`그리기: ${info.render_mode === 'layout' ? '한컴 조판 그대로' : info.render_mode === 'reflow' ? '자체 조판(실제와 쪽 나눔이 다를 수 있음)' : '그릴 수 없음'}`)
  if (page) lines.push(`보고 있는 쪽: ${page}`)
  if (selection?.block) {
    lines.push(`선택: ${selection.cell || selection.block}${selText ? ` "${String(selText).slice(0, 120)}"` : ''}`)
  } else {
    lines.push('선택한 블록 없음')
  }
  if (viewingOld) lines.push('지금은 지난 버전을 보는 중이라 고칠 수 없음')
  lines.push(canEdit ? '편집 가능' : '보기 전용(도구로 고치지 말고 제안만)')
  return lines.join('\n')
}
